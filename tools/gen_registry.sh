#!/bin/bash
# regenerate src/patterns/_registry.c from src/patterns/NNN_*.c
cd "$(dirname "$0")/../src/patterns" || exit 1
files=$(ls [0-9][0-9][0-9]_*.c [0-9][0-9][0-9].c 2>/dev/null | sort)
{
  echo '/* auto-generated by tools/gen_registry.sh — do not edit */'
  echo '#include "../engine/jellydazzle.h"'
  for f in $files; do
    n="${f:0:3}"
    echo "extern void pattern_${n}(uint32_t*, int, int, int, int, uint32_t, const uint32_t*);"
  done
  echo 'const jd_pattern_fn jd_patterns[] = {'
  for f in $files; do echo "    pattern_${f:0:3},"; done
  echo '};'
  # names, so the ABOUT card can say what is on screen right now
  echo 'const char *const jd_pattern_names[] = {'
  for f in $files; do
    nm="${f:4}"; nm="${nm%.c}"; nm="${nm//_/ }"
    echo "    \"${f:0:3} ${nm}\","
  done
  echo '};'
  # SHAPE FAMILY per pattern. Measured across the shipping library, 20% of
  # patterns are string-art X/curve-weaves and another 20% are radial mandalas
  # — so with four layers up, seeing an X was close to certain every frame.
  # The compositor uses this to keep two layers of the SAME SHAPE off screen
  # together, exactly as it already does for hue.
  #   0 other  1 X/string  2 grid/panel  3 radial  4 field/flow
  #   5 particle  6 lightning  7 tunnel/depth  8 fractal
  # Fractals are their own family for two reasons: they share a look (escape
  # structure and filigree), and several cost 3-4 ms a frame, so two of them up
  # together would be both repetitive and expensive.
  echo 'const unsigned char jd_pattern_family[] = {'
  for f in $files; do
    nm=$(echo "${f:4}" | tr 'A-Z' 'a-z')
    fam=0
    case "$nm" in
      *mandel*|*julia*|*burning_ship*|*newton*|*lyapunov*|*buddhabrot*|*flame*|*fractal*|*apollon*|*kleinian*) fam=8;;
      *lissa*|*string*|*harmonograph*|*spiro*|*curve*|*weave*|*braid*|*plait*|*cord*|*thread*|*loom*|*web*|*envelope*|*cardioid*|*epicycle*|*pendulum*|*maurer*|*guilloche*|*knot*|*hopf*|*villarceau*|*steiner*|*doyle*|*loxodrome*) fam=1;;
      *quilt*|*tile*|*truchet*|*mosaic*|*greek*|*panel*|*lattice*|*tartan*|*checker*|*grid*|*patch*|*cloth*|*pentagrid*|*craquelure*|*facet*) fam=2;;
      *mandala*|*rosette*|*kaleido*|*fold*|*pinwheel*|*spiral*|*fan*|*burst*|*star*|*flower*|*bloom*|*petal*|*rose*|*octa*|*hex*|*spoke*|*wedge*|*iris*|*aperture*) fam=3;;
      *plasma*|*silk*|*flow*|*current*|*aurora*|*curtain*|*smoke*|*ink*|*veil*|*marbl*|*caustic*|*ripple*|*wave*|*moire*|*interf*|*noise*|*drift*|*swirl*|*vortex*) fam=4;;
      *spark*|*rain*|*snow*|*ember*|*firefly*|*pollen*|*dust*|*mote*|*glint*|*swarm*|*plankton*|*comet*|*seed*|*twinkle*|*lantern*|*starfield*|*meteor*|*firework*) fam=5;;
      *lightning*|*bolt*|*tesla*|*elmo*|*filament*) fam=6;;
      *tunnel*|*corridor*|*wormhole*|*pillar*|*hall*|*warp*|*droste*|*tesseract*|*relief*) fam=7;;
    esac
    # 3.4: BLOCK RANGES beat keywords.  The library was written in themed runs
    # and the keywords only caught 29 of the 72 lightning files (ground_strike,
    # jacobs_ladder, corona_disc, upward_streamers… all read as 'other'), which
    # is why the spark slot kept handing back a bolt.  The same for the matrix
    # rain (572-581), the gear train (557-571), the particle run (582-601) and
    # the 336-468 ground kit, whose unmatched members default to field/flow.
    #   9 matrix/code-rain   10 gears/mechanical   11 creatures
  #  12 rings   13 sky/space   14 material/textile/paint   15 nature/land/water
    n=$((10#${f:0:3}))
    if   [ $n -ge 469 ] && [ $n -le 540 ]; then fam=6
    elif [ $n -ge 572 ] && [ $n -le 581 ]; then fam=9
    elif [ $n -ge 557 ] && [ $n -le 571 ]; then fam=10
    elif [ $n -ge 582 ] && [ $n -le 601 ]; then fam=5
    # 3.5.9: two new blocks. CREATURES (611-628) are their own family because
    # they share an unmistakable look — a recognisable animal in motion — and
    # two of them on screen at once reads as a menagerie rather than variety.
    # The new FRACTALS (629-638) join the existing fractal family 8 so they
    # inherit its no-two-together rule and its cost separation.
    elif [ $n -ge 611 ] && [ $n -le 628 ]; then fam=11
    # 3.6.6: 639-642 (multibrot, nova, neon mandel, clifford) from fractals.md
    elif [ $n -ge 629 ] && [ $n -le 642 ]; then fam=8
    fi
    # (the 336-468 ground kit keeps its keyword families only: those are
    #  grounds, and the compositor's kit-alternation rule handles their look)
    # 3.6: FAMILY 0 WAS A THIRD OF THE LIBRARY. 200 of 638 patterns fell through
    # every rule above into "other" — and the compositor exempts family 0 from
    # the on-screen clash test, so look-alikes inside it could share the screen.
    # J's 2026-10-10 screenshot was exactly that: 099 racetrack drums, with
    # 089 oval drums / 418 breathing rings / 420 elliptic rings / 544 nested
    # rings all sitting untagged beside it. These rules only touch patterns
    # still at 0, so every existing assignment above is unchanged.
    #   11 creatures (pre-3.5.9 animals join the new ones)
    #   12 rings / concentric   13 sky, weather, space
    #   14 material, textile, stone, paint   15 nature, land, water
    if [ $fam -eq 0 ]; then
      case "$nm" in
        *turing*|*physarum*|*reiter*) fam=15;;   # reaction-diffusion / growth: organic, and "tuRING" must not match rings
        *hummingbird*|*koi*|*crane*|*jelly_bell*|*comb_jelly*|*anemone*) fam=11;;
        *_ring*|*rings*|ring_*|*drum*|*target*|*bullseye*|*nested*|*orbit*|*rounded_square*|*harmonic_orb*|*harmonic_shell*|*lobes*) fam=12;;
        *cloud*|*fog*|*mist*|*storm*|*sunset*|*twilight*|*overcast*|*shimmer*|*god_ray*|*halo*|*dapple*|*cirrus*|*nebula*|*supernova*|*milky*|*stellar*|*light_leak*|*bokeh*|*wisp*|*dawn*) fam=13;;
        *velvet*|*metal*|*steel*|*glass*|*terrazzo*|*tesserae*|*plates*|*agate*|*malachite*|*onyx*|*lace*|*gauze*|*tulle*|*tapestry*|*woven*|*rope*|*chain_mail*|*drape*|*dye*|*shibori*|*wash*|*gouache*|*granulation*|*suminagashi*|*brush*|*paisley*|*argyle*|*eyelet*|*doily*|*sheen*|*scales*|*feathers*|*peacock*|*cathedral_panes*|*gradient_mesh*|*prism*) fam=14;;
        *coral*|*kelp*|*moss*|*fern*|*frost*|*ice*|*vine*|*root*|*pine*|*wisteria*|*lotus*|*lily*|*fungal*|*sponge*|*membrane*|*cell_tissue*|*sinew*|*worm*|*dune*|*canyon*|*river*|*lakebed*|*raked*|*terraced*|*topo*|*bathymetry*|*isobar*|*contours*|*sand*|*water*|*tide*|*foam*|*bubble*|*soap*|*lava*|*oil*|*grass*|*wing_veins*|*moth_wing*|*phyllotaxis*|*honeycomb*|*plume*|*strata*) fam=15;;
      esac
    fi
    echo "    $fam,"
  done
  echo '};'
  echo "const int jd_pattern_count = $(echo "$files" | wc -w | tr -d ' ');"
} > _registry.c
echo "registry: $(echo "$files" | wc -w | tr -d ' ') patterns"
